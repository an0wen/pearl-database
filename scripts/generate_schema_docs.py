"""Generate the single Sphinx data-format reference page."""
import argparse
from pathlib import Path
from schema_utils import ROOT, load_schemas, sections, toml_value

def rst_text(value):
    return value.replace('\\', '\\\\').replace('*', '\\*')


OUTPUT = ROOT / 'docs' / 'source' / 'data_format' / 'reference.rst'


def generate(output=OUTPUT):
    lines = ['.. Generated by scripts/generate_schema_docs.py; edit schemas/*.toml instead.', '',
             'Data file reference', '===================', '',
             'These tables describe source, EOS, and thermo metadata TOML files.',
             'Values shown are examples, not defaults.','',
             'Required means the field must be present. We try to keep a minimum number of required fields to encourage new entries, and update later if necessary.', '',
             'You can run ``python scripts/check_schema_coverage.py`` to verify that all entries existing in the database are covered by the schemas described below.', '',
             '.. contents:: On this page', '   :local:', '   :depth: 2', '']
    for kind, schema in load_schemas().items():
        title = schema['title']
        lines += [title, '-' * len(title), '', rst_text(schema['description']), '',
                  f'Schema: ``schemas/{kind}.toml``. Template: ``data/_template/{schema["template_file"]}``.', '']
        for section, fields in sections(schema).items():
            title = section or 'Top-level fields'
            lines += [title, '~' * len(title), '']
            note = schema.get('sections', {}).get(section, {}).get('description')
            if note:
                lines += [note, '']
            if not fields:
                continue
            lines += ['.. list-table::', '   :header-rows: 1', '   :class: schema-fields', '',
                      '   * - Field', '     - Description', '     - Accepted values',
                      '     - Unit', '     - Required', '     - Example']
            for name, field in fields.items():
                accepted = field['type']
                if field.get('allow_list'):
                    accepted += ' or list of ' + field['type']
                if field.get('format'):
                    accepted += f' ({field["format"]})'
                lines += [f'   * - ``{name}``', f'     - {field["description"]}',
                          f'     - {accepted}', f'     - {field["unit"]}',
                          '     - ' + ('Yes' if field['required'] else 'No'),
                          f'     - ``{toml_value(field["example"])}``']
            lines.append('')
    output = Path(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text('\n'.join(lines), encoding='utf-8')
    return output


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=OUTPUT)
    print(f'Generated {generate(parser.parse_args().output)}')
